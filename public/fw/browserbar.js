// Makes the browser bar work: back / forward / reload, the address field and
// the tab. The server draws the bar (lib/browserbar.js) and the address field
// is an ordinary form to /go, so this only adds what a real browser does on
// top: history buttons, select-all on focus, Escape to revert, the page's
// title and favicon in the tab, and the loading state.
(() => {
  "use strict";
  const bar = document.querySelector("foogle-bar");
  const root = bar?.shadowRoot;
  if (!root || bar.__fb) return;
  bar.__fb = true;
  const $ = (sel) => root.querySelector(sel);
  const input = $("input");
  const path = $(".url .p");
  const address = input.value; // this page's URL as the bar shows it, less any #hash

  // ---------- back, forward, reload / stop ----------
  const back = $(".back");
  const fwd = $(".fwd");
  const nav = window.navigation; // knows about forward history; plain history doesn't
  const syncButtons = () => {
    back.disabled = nav ? !nav.canGoBack : history.length < 2;
    fwd.disabled = nav ? !nav.canGoForward : false;
  };
  back.addEventListener("click", () => history.back());
  fwd.addEventListener("click", () => history.forward());
  $(".reload").addEventListener("click", () => {
    if (!bar.hasAttribute("loading")) return location.reload();
    window.stop();
    loaded();
  });

  // ---------- the address field ----------
  const shown = () => address + location.hash;
  const showAddress = () => {
    input.value = shown();
    const p = path.dataset.path;
    path.textContent = (p === "/" && !location.hash ? "" : p) + location.hash;
  };
  // Select everything on the first click, like an omnibox; a second click
  // places the caret. A mouse click would place the caret after focusing, so
  // it focuses by hand; a tap or Tab selects once focus has landed.
  let pointer = "";
  let focusedAt = 0;
  input.addEventListener("pointerdown", (e) => { pointer = e.pointerType; });
  input.addEventListener("mousedown", (e) => {
    if (pointer !== "mouse" || e.button !== 0 || root.activeElement === input) return;
    e.preventDefault();
    input.focus();
    input.select();
  });
  input.addEventListener("focus", () => {
    focusedAt = Date.now();
    setTimeout(() => { if (root.activeElement === input && input.selectionStart === input.selectionEnd) input.select(); }, 0);
  });
  input.addEventListener("mouseup", (e) => {
    if (Date.now() - focusedAt < 400) e.preventDefault();
  });
  input.addEventListener("blur", showAddress);
  input.addEventListener("keydown", (e) => {
    if (e.key !== "Escape") return;
    if (input.value !== shown()) {
      input.value = shown();
      input.select();
    } else input.blur();
  });
  $("form").addEventListener("submit", (e) => {
    if (!input.value.trim()) {
      e.preventDefault();
      showAddress();
    }
  });
  addEventListener("hashchange", () => { showAddress(); syncButtons(); });
  addEventListener("pageshow", () => { showAddress(); syncButtons(); });
  // Results pages prerender /web/ links on hover; history is only this
  // page's once it is shown.
  document.addEventListener("prerenderingchange", syncButtons);

  // ---------- the tab ----------
  const tab = $(".tab");
  const title = $(".title");
  const syncTitle = () => {
    const t = document.title.trim();
    if (t && t !== title.textContent) {
      title.textContent = t;
      tab.title = t;
    }
  };
  // A generated site's favicon is the logo mark its header draws.
  const syncIcon = () => {
    const mark = bar.hasAttribute("data-site") && document.querySelector("svg.mark");
    if (mark) $(".fav").src = `data:image/svg+xml,${encodeURIComponent(new XMLSerializer().serializeToString(mark))}`;
  };
  // The page streams in: its <title> arrives with its first generated bytes.
  let queued = false;
  const watcher = new MutationObserver(() => {
    if (queued) return;
    queued = true;
    requestAnimationFrame(() => { queued = false; syncTitle(); });
  });
  function loaded() {
    watcher.disconnect();
    bar.removeAttribute("loading");
    syncTitle();
    syncIcon();
  }

  // ---------- keyboard scrolling ----------
  // Pages scroll inside <body> under the bar (see lib/browserbar.js), which
  // the browser's own Space / Page Down / arrow keys don't reach until
  // something in the page is clicked.
  const STEPS = { PageDown: 0.875, PageUp: -0.875, " ": 0.875, ArrowDown: 40, ArrowUp: -40, Home: -Infinity, End: Infinity };
  addEventListener("keydown", (e) => {
    const body = document.body;
    const step = STEPS[e.key];
    if (step === undefined || e.defaultPrevented || e.target !== body || e.altKey || e.ctrlKey || e.metaKey) return;
    if (getComputedStyle(body).overflowY !== "auto") return;
    e.preventDefault();
    let dy = Math.abs(step) < 1 ? step * body.clientHeight : Number.isFinite(step) ? step : Math.sign(step) * body.scrollHeight;
    if (e.key === " " && e.shiftKey) dy = -dy;
    body.scrollBy({ top: dy, behavior: "smooth" });
  });

  // ---------- scroll position ----------
  // Pages scroll inside <body> under the bar (see lib/browserbar.js), which
  // browsers don't restore on back, forward or reload the way they restore a
  // window's scroll. Keep it per URL for the session.
  const scrollKey = `fb-scroll:${location.href}`;
  addEventListener("pagehide", () => {
    try { sessionStorage.setItem(scrollKey, String(document.body.scrollTop)); } catch { /* storage off */ }
  });
  const restoreScroll = () => {
    const how = performance.getEntriesByType?.("navigation")[0]?.type;
    if (how !== "back_forward" && how !== "reload") return;
    let y = 0;
    try { y = Number(sessionStorage.getItem(scrollKey)) || 0; } catch { /* storage off */ }
    if (y && document.body.scrollTop < 1) document.body.scrollTo({ top: y, behavior: "instant" });
  };

  showAddress();
  syncButtons();
  syncTitle();
  if (document.readyState === "loading") {
    watcher.observe(document.documentElement, { childList: true, subtree: true });
    document.addEventListener("DOMContentLoaded", () => { loaded(); restoreScroll(); }, { once: true });
  } else {
    loaded();
    restoreScroll();
  }
})();
